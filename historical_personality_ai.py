# ============================================================
# 2. 歴史人物プロフィール作成関数
#
# 100人×10項目を全部手入力すると管理が大変なので、
# 「特に強い特徴」「比較的弱い特徴」を指定して
# 10軸を自動生成します。
#
# 数値は歴史学的・心理学的測定値ではありません。
# ============================================================

def make_person(name, category, highs, lows=()):

    # 名前から毎回同じ小さな差を作る
    seed = sum(ord(c) for c in name)

    traits = {}

    for i, trait in enumerate(TRAITS):

        # 基本値 54〜66程度
        traits[trait] = 54 + ((seed + i * 7) % 13)

    # 強い特徴
    high_values = [94, 89, 84, 80]

    for i, trait in enumerate(highs):
        if trait in traits:
            traits[trait] = high_values[min(i, 3)]

    # 比較的弱い特徴
    low_values = [34, 41, 46]

    for i, trait in enumerate(lows):
        if trait in traits:
            traits[trait] = low_values[min(i, 2)]

    return {
        "name": name,
        "category": category,
        "traits": traits
    }


