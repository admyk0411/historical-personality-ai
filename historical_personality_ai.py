# 10. スコア
#
# 各項目10問 × 最大10点 = 最大100点
# そのため、そのまま0〜100になります。
# ============================================================

def normalized_scores(data):

    scores = {}

    answered_by_trait = {
        trait: 0
        for trait in TRAITS
    }

    raw_by_trait = {
        trait: 0
        for trait in TRAITS
    }

    for answer in data["answers"]:

        trait = answer["trait"]

        answered_by_trait[trait] += 1
        raw_by_trait[trait] += answer["score"]

    for trait in TRAITS:

        answered = answered_by_trait[trait]

        if answered == 0:
            scores[trait] = 0
        else:

            maximum = answered * 10

            scores[trait] = round(
                raw_by_trait[trait]
                / maximum
                * 100
            )

    return scores


# ============================================================
# 11. 人物との類似度
#
# 10軸の平均との差を使います。
# 100% = アプリ内プロフィールが完全一致
# ============================================================

def calculate_similarity(user_scores, person):

    squared_differences = []

    for trait in TRAITS:

        difference = (
            user_scores[trait]
            - person["traits"][trait]
        )

        squared_differences.append(
            difference ** 2
        )

    rms = math.sqrt(
        sum(squared_differences)
        / len(TRAITS)
    )

    similarity = 100 - rms

    return round(
        max(0, min(100, similarity)),
        1
    )


# ============================================================
# 12. TOP人物を取得
# ============================================================

def find_top_people(user_scores, limit=5):

    results = []

    for person in PEOPLE:

        similarity = calculate_similarity(
            user_scores,
            person
        )

        results.append({
            "person": person,
            "similarity": similarity
        })

    results.sort(
        key=lambda x: x["similarity"],
        reverse=True
    )

    return results[:limit]


# ============================================================
# 13. 人物との共通点
# ============================================================

def closest_traits(user_scores, person, limit=3):

    result = []

    for trait in TRAITS:

        difference = abs(
            user_scores[trait]
            - person["traits"][trait]
        )

        result.append(
            (trait, difference)
        )

    result.sort(
        key=lambda x: x[1]
    )

    return [
        trait
        for trait, _ in result[:limit]
    ]


# ============================================================
# 14. 人物との違い
# ============================================================

def different_traits(user_scores, person, limit=3):

    result = []

    for trait in TRAITS:

        difference = abs(
            user_scores[trait]
            - person["traits"][trait]
        )

        result.append(
            (
                trait,
                difference,
                user_scores[trait],
                person["traits"][trait]
            )
        )

    result.sort(
        key=lambda x: x[1],
        reverse=True
    )

    return result[:limit]


