def build_questions():

    questions = []

    number = 1

    for trait in TRAITS:

        bank = QUESTION_BANKS[trait]

        for question, a, b, high_choice in bank:

            questions.append({
                "number": number,
                "trait": trait,
                "question": question,
                "a": a,
                "b": b,
                "high_choice": high_choice
            })

            number += 1

    return questions


